"""World Model Subsystem for CDM-1 Cognitive AI Engine.
Maintains an explicit internal representation of the operational environment,
its entities, relations, active constraints, and transition dynamics S_{t+1} = T(S_t, A_t).
"""

from typing import Dict, List, Optional, Any, Tuple
import time
from cdm.cognitive.state import WorldState, WorldEntity, WorldRelation


class WorldModel:
    """Explicit world model representing the operational environment and simulating action transitions.
    Strictly isolates observed facts, inferred state, counterfactual simulated state, and predicted future state.
    """

    def __init__(self, tenant_id: str = "default_tenant", session_id: str = "default_session"):
        self.tenant_id = tenant_id
        self.session_id = session_id
        self.state = WorldState(tenant_id=tenant_id, session_id=session_id)

    def record_observed_fact(self, key: str, value: Any) -> None:
        """Records ground-truth empirical facts directly observed from perception or verified telemetry."""
        self.state.observed_facts[key] = value

    def record_inferred_state(self, key: str, value: Any) -> None:
        """Records deductions and inferences derived from active rules, constraints, or reasoning."""
        self.state.inferred_state[key] = value

    def record_predicted_future_state(self, predictions: Dict[str, Any]) -> None:
        """Records probabilistic outcome forecasts generated by the trained neural decision core."""
        self.state.predicted_future_state.update(predictions)

    def update_entity(
        self,
        entity_id: str,
        entity_type: str,
        properties: Dict[str, Any],
        inferred_properties: Optional[Dict[str, Any]] = None,
        uncertainty: float = 0.0,
    ) -> WorldEntity:
        """Adds or updates an entity in the world state."""
        existing = self.state.entities.get(entity_id)
        if existing:
            existing.properties.update(properties)
            if inferred_properties:
                existing.inferred_properties.update(inferred_properties)
            existing.uncertainty = uncertainty
            existing.last_updated = time.time()
            return existing
        else:
            entity = WorldEntity(
                entity_id=entity_id,
                entity_type=entity_type,
                properties=properties,
                inferred_properties=inferred_properties or {},
                uncertainty=uncertainty,
                last_updated=time.time(),
            )
            self.state.entities[entity_id] = entity
            self._update_overall_uncertainty()
            return entity

    def add_relation(self, source_id: str, relation_type: str, target_id: str, confidence: float = 1.0) -> None:
        """Adds or updates a directed relation between entities."""
        # Avoid duplicate relations
        for r in self.state.relations:
            if r.source_id == source_id and r.relation_type == relation_type and r.target_id == target_id:
                r.confidence = confidence
                return
        self.state.relations.append(
            WorldRelation(source_id=source_id, relation_type=relation_type, target_id=target_id, confidence=confidence)
        )

    def set_environment_metric(self, metric_name: str, value: float) -> None:
        """Updates a global environment metric (e.g., system latency, remaining SLA, error rate)."""
        self.state.environment_metrics[metric_name] = value

    def register_constraint(self, constraint: str) -> None:
        """Registers an active operational or policy constraint."""
        if constraint not in self.state.active_constraints:
            self.state.active_constraints.append(constraint)

    def simulate_transition(
        self,
        action: str,
        action_params: Optional[Dict[str, Any]] = None,
        base_state: Optional[WorldState] = None,
    ) -> WorldState:
        """Counterfactual forward transition model: S_{t+1} = T(S_t, Action).
        Simulates how taking a candidate action alters the environment state without mutating ground truth.
        Accepts an optional base_state for sequential multi-step transition chaining.
        """
        params = action_params or {}
        simulated = (base_state or self.state).model_copy(deep=True)

        action_clean = action.lower()
        transition_delta = {"action": action, "parameters": params}
        if "escalate" in action_clean:
            # Escalation reduces SLA remaining hours and increases operational urgency
            sla = simulated.environment_metrics.get("sla_remaining_hours", 12.0)
            simulated.environment_metrics["sla_remaining_hours"] = max(0.5, sla * 0.5)
            simulated.environment_metrics["escalation_active"] = 1.0
            transition_delta["sla_impact"] = -0.5 * sla
        elif "refund" in action_clean:
            # Refund adjusts monetary risk to settled
            simulated.environment_metrics["refund_issued"] = 1.0
            simulated.environment_metrics["monetary_risk"] = 0.0
            simulated.environment_metrics["monetary_value_usd"] = 0.0
            transition_delta["monetary_settlement"] = True
        elif "block" in action_clean or "quarantine" in action_clean:
            # Security quarantine protects system integrity
            simulated.environment_metrics["system_exposure"] = 0.0
            simulated.environment_metrics["service_disruption_risk"] = 0.8
            transition_delta["quarantine_enforced"] = True
        elif "isolate" in action_clean:
            # Cluster isolation isolates network and lowers exposure
            simulated.environment_metrics["system_exposure"] = 0.1
            simulated.environment_metrics["cluster_isolated"] = 1.0
            transition_delta["cluster_isolated"] = True
        elif "auto_resolve" in action_clean:
            # Resolution decreases pending queue
            simulated.environment_metrics["resolved"] = 1.0
            transition_delta["queue_resolved"] = True
        elif "stabilize" in action_clean:
            simulated.environment_metrics["vital_instability"] = 0.0
            simulated.environment_metrics["patient_stable"] = 1.0
            transition_delta["vital_stabilized"] = True
        elif "triage" in action_clean:
            simulated.environment_metrics["triage_completed"] = 1.0
            transition_delta["triage_completed"] = True

        simulated.simulated_state[f"transition_{action}"] = transition_delta
        return simulated

    def record_transition(
        self,
        session_id: str,
        action_name: str,
        action_args: Dict[str, Any],
        outcome_observed: Dict[str, Any],
        tenant_id: str = "default_tenant",
    ) -> None:
        """Records an actual physical or execution transition outcome into observed facts and metrics."""
        self.record_observed_fact(f"action_executed_{action_name}", True)
        self.record_observed_fact(f"last_action_args_{action_name}", action_args)
        self.record_observed_fact(f"last_action_outcome_{action_name}", outcome_observed)

        if outcome_observed.get("success"):
            self.set_environment_metric(f"{action_name}_last_status", 1.0)
            if "write" in action_name or "create" in action_name:
                self.set_environment_metric("files_modified_count", self.state.environment_metrics.get("files_modified_count", 0.0) + 1.0)
            elif "resolve" in action_name:
                self.set_environment_metric("resolved", 1.0)
        else:
            self.set_environment_metric(f"{action_name}_last_status", 0.0)
            self.set_environment_metric("failed_actions_count", self.state.environment_metrics.get("failed_actions_count", 0.0) + 1.0)

    def _update_overall_uncertainty(self) -> None:
        """Computes average uncertainty across all world entities."""
        if not self.state.entities:
            self.state.overall_state_uncertainty = 0.0
            return
        total = sum(e.uncertainty for e in self.state.entities.values())
        self.state.overall_state_uncertainty = total / len(self.state.entities)

    def get_state(self, session_id: Optional[str] = None) -> WorldState:
        """Returns the current world state."""
        return self.state.model_copy(deep=True)
